const I18N = {
  lang: 'ko',
  init() {
    this.lang = LS.get('lang', 'ko');
    this.applyFont(LS.get('fontSize', 'm'));
    this.build();
  },
  build() {
    const li = { en: 1, zh: 2, ja: 3 }[this.lang];
    this.exact = new Map(); this.sub = []; this.rules = [];
    if (!li) return;
    for (const r of EXACT) this.exact.set(r[0], r[li]);
    this.sub = SUB.map(r => [r[0], r[li]]).sort((a, b) => b[0].length - a[0].length);
    this.subRe = new RegExp(this.sub.map(([k]) => k.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')).join('|'), 'g');
    this.subMap = new Map(this.sub);
    this.rules = RULES.map(([re, arr]) => [re, arr[li - 1]]);
  },
  setLang(l) { this.lang = l; LS.set('lang', l); document.documentElement.lang = l; this.build(); },
  applyFont(k) {
    const f = (FONT_SIZES.find(x => x[0] === k) || FONT_SIZES[1])[1];
    LS.set('fontSize', k);
    document.documentElement.style.setProperty('--zoom', f);
    document.body && (document.body.style.zoom = f);
  },
  str(s) {
    if (this.lang === 'ko' || !s) return s;
    const t = s.trim();
    if (!t || !/[가-힣]/.test(t)) return s;
    if (this.exact.has(t)) return s.replace(t, this.exact.get(t));
    if (t.startsWith('›') && t.length > 2) {   // 위치 표시줄: "› 개념 정리 › 시험" 처럼 조각마다 번역
      return s.replace(t, t.split('›').map(p => { const q = p.trim(); return q ? ' ' + (this.exact.get(q) || q) + ' ' : ''; }).join('›').trim());
    }
    for (const [re, rep] of this.rules) if (rep && re.test(t)) {
      // 규칙의 $1 등에 들어가는 한국어 조각도 사전에서 다시 찾아 바꿈
      return s.replace(t, t.replace(re, (...m) => rep.replace(/\$(\d)/g, (_, k) => { const g = m[Number(k)] || ''; return this.exact.get(g.trim()) || g; })));
    }
    return s.replace(this.subRe, m => this.subMap.get(m));
  },
  // 화면 전체(또는 일부)에서 메뉴·안내 문구만 바꿈
  apply(root) {
    if (this.lang === 'ko') return;
    const skip = el => el.closest('[data-notr], .quote, textarea, script, style');
    const w = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
    const nodes = [];
    while (w.nextNode()) nodes.push(w.currentNode);
    for (const n of nodes) {
      if (!n.parentElement || skip(n.parentElement)) continue;
      const v = this.str(n.nodeValue);
      if (v !== n.nodeValue) n.nodeValue = v;
    }
    root.querySelectorAll('[placeholder],[title],[aria-label]').forEach(el => {
      if (el.closest('[data-notr]')) return;
      for (const a of ['placeholder', 'title', 'aria-label']) if (el.hasAttribute(a)) el.setAttribute(a, this.str(el.getAttribute(a)));
    });
  },
};

